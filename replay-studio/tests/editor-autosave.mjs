import {chromium,expect} from '@playwright/test';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto('http://127.0.0.1:4173');
  await page.locator('#project-input').setInputFiles(path.join(root,'test-results/full.replay'));
  await expect(page.locator('.note-card')).toHaveCount(2);
  await expect(page.locator('.track-heading-row .timeline-label #add-track')).toBeVisible();
  await expect(page.locator('.timeline-actions #add-track')).toHaveCount(0);
  await page.locator('#add-track').click();await page.locator('#track-name-input').fill('位置验证轨道');await page.locator('#track-submit').click();
  await expect(page.locator('.track-row')).toHaveCount(5);
  const first=page.locator('.note-card').first(),second=page.locator('.note-card').nth(1);
  await first.locator('[data-edit-marker]').first().click();
  await expect(page.locator('#save-marker')).toBeHidden();
  await page.locator('#marker-text').fill('停止输入后自动保存');
  await expect(first.locator('p')).toHaveText('停止输入后自动保存');
  await expect(page.locator('#marker-save-hint')).toHaveText('已自动保存');
  await page.locator('#marker-text').fill('切换标记前立即保存');
  const otherText=await second.locator('p').textContent();
  await second.locator('[data-edit-marker]').first().click();
  await expect(first.locator('p')).toHaveText('切换标记前立即保存');
  await expect(page.locator('#marker-text')).toHaveValue(otherText);
  await page.locator('#marker-text').fill('第二条也自动保存');
  await page.locator('#marker-at').click();
  await expect(second.locator('p')).toHaveText('第二条也自动保存');
  await page.locator('#marker-at').fill('00:00:07.000');
  await page.locator('#marker-text').click();
  await expect(second.locator('[data-seek-marker]')).toHaveText('00:00:07.000');
  await page.locator('#undo').click();await expect(second.locator('[data-seek-marker]')).toHaveText('00:00:06.000');
  await expect(page.locator('.note-card')).toHaveCount(2);
  await page.locator('#mark-current').click();await page.locator('#marker-text').fill('未提交的新标记');await page.locator('#marker-at').click();
  await expect(page.locator('.note-card')).toHaveCount(2);
  await first.locator('[data-edit-marker]').first().click();await page.locator('#marker-text').fill('刷新前的最后修改');
  await page.reload();await page.locator('#restore-draft').click();
  await expect(page.locator('.note-card').first().locator('p')).toHaveText('刷新前的最后修改');
  await expect(page.locator('.note-card')).toHaveCount(2);
  await page.screenshot({path:path.join(root,'test-results/editor-update.png')});
  if(errors.length)throw Error(errors.join('\n'));
  console.log('PASS: left track control, idle/blur autosave, immediate note switching, timestamp edits, undo, no duplicate/new autosave, refresh recovery.');
}finally{await browser.close();}
